func TestRebindSQLitePassthrough(t *testing.T) {
	q := `INSERT INTO t(a,b) VALUES(?,?)`
	if got := Rebind(SQLite, q); got != q {
		t.Fatalf("sqlite rebind changed query: %s", got)
	}
}

func TestRebindPostgres(t *testing.T) {
	cases := []struct{ in, want string }{
		{`SELECT * FROM t WHERE a=? AND b=?`, `SELECT * FROM t WHERE a=$1 AND b=$2`},
		{`UPDATE t SET x=? WHERE id=?`, `UPDATE t SET x=$1 WHERE id=$2`},
		{`SELECT 1`, `SELECT 1`},
	}
	for _, c := range cases {
		if got := Rebind(Postgres, c.in); got != c.want {
			t.Fatalf("Rebind(%q) = %q, want %q", c.in, got, c.want)
		}
	}
}

func TestSQLiteDSN(t *testing.T) {
	got := SQLiteDSN(`C:/data/agent.db`)
	want := "file:C:/data/agent.db?_pragma=busy_timeout(5000)&_pragma=journal_mode(DELETE)&_pragma=foreign_keys(ON)"
	if got != want {
		t.Fatalf("SQLiteDSN = %q, want %q", got, want)
	}
}

func TestIdentityPK(t *testing.T) {
	if got := IdentityPK(SQLite); got != "INTEGER PRIMARY KEY AUTOINCREMENT" {
		t.Fatalf("sqlite identity = %q", got)
	}
	if got := IdentityPK(Postgres); got != "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" {
		t.Fatalf("postgres identity = %q", got)
	}
}

