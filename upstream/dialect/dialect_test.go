// Open sqlite 裸路径自动补 pragma，且可建表读写（驱动注册与 DSN 组装冒烟）。
func TestOpenSQLiteRoundtrip(t *testing.T) {
	db, err := Open(SQLite, filepath.Join(t.TempDir(), "t.db"))
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`CREATE TABLE t(id INTEGER PRIMARY KEY, v TEXT NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`INSERT INTO t(v) VALUES(?)`, "x"); err != nil {
		t.Fatal(err)
	}
	var v string
	if err := db.QueryRow(`SELECT v FROM t WHERE id=?`, 1).Scan(&v); err != nil {
		t.Fatal(err)
	}
	if v != "x" {
		t.Fatalf("v = %q", v)
	}
}

// Open sqlite 已带 file: 前缀的 DSN 原样使用（不二次包装）。
func TestOpenSQLiteDSNPassthrough(t *testing.T) {
	path := filepath.Join(t.TempDir(), "t.db")
	dsn := SQLiteDSN(path)
	db, err := Open(SQLite, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`SELECT 1`); err != nil {
		t.Fatal(err)
	}
}
